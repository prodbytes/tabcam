# Sourced by the run scripts. DART_DEFINES holds a --dart-define for each
# allowed setting: from the environment when it's set there (scripts/deploy.sh
# sets the stage), otherwise from the repo's .env (see .env.example).
#
# Only the names below are passed: anything given to Flutter is compiled
# into the app (readable in the web bundle), so secrets in .env must never
# be listed here. Add public identifiers only.
_allowed=(TABSCAN_STAGE GOOGLE_WEB_CLIENT_ID GOOGLE_IOS_CLIENT_ID AWS_REGION COGNITO_IDENTITY_POOL_ID USER_DATA_BUCKET SHARE_API_URL)
_env="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.env"
DART_DEFINES=()
for _name in "${_allowed[@]}"; do
  _value="${!_name:-}"
  if [[ -z "$_value" && -f "$_env" ]]; then
    _value="$(sed -n "s/^${_name}=//p" "$_env" | tail -1)"
  fi
  [[ -n "$_value" ]] && DART_DEFINES+=(--dart-define="${_name}=${_value}")
done

# iOS settings that aren't dart-defines go to a git-ignored xcconfig that
# Debug.xcconfig and Release.xcconfig include, so nothing personal or
# project-specific is committed:
# - the developer's own signing team (IOS_DEVELOPMENT_TEAM);
# - the reversed iOS client ID (GOOGLE_IOS_CLIENT_ID), Google sign-in's
#   return URL scheme in Info.plist.
_ios="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/tabscan_app/ios/Flutter/Private.xcconfig"
_lines=()
_value="${IOS_DEVELOPMENT_TEAM:-}"
[[ -z "$_value" && -f "$_env" ]] && _value="$(sed -n 's/^IOS_DEVELOPMENT_TEAM=//p' "$_env" | tail -1)"
if [[ "$_value" =~ ^[A-Z0-9]{10}$ ]]; then
  _lines+=("DEVELOPMENT_TEAM=$_value")
elif [[ -n "$_value" ]]; then
  echo "warning: IOS_DEVELOPMENT_TEAM isn't a 10-character team ID; iOS stays unsigned" >&2
fi
_value="${GOOGLE_IOS_CLIENT_ID:-}"
[[ -z "$_value" && -f "$_env" ]] && _value="$(sed -n 's/^GOOGLE_IOS_CLIENT_ID=//p' "$_env" | tail -1)"
if [[ "$_value" =~ ^[0-9]+-[0-9a-z]+\.apps\.googleusercontent\.com$ ]]; then
  _lines+=("GOOGLE_REVERSED_CLIENT_ID=com.googleusercontent.apps.${_value%.apps.googleusercontent.com}")
elif [[ -n "$_value" ]]; then
  echo "warning: GOOGLE_IOS_CLIENT_ID isn't a Google client ID; iOS sign-in won't return to the app" >&2
fi
if (( ${#_lines[@]} )); then
  printf '// Generated by scripts/dart-defines.sh from .env; git-ignored.\n' > "$_ios"
  printf '%s\n' "${_lines[@]}" >> "$_ios"
fi
unset _allowed _env _name _value _ios _lines
