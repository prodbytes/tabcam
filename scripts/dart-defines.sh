# Sourced by the run scripts. DART_DEFINES holds a --dart-define for each
# allowed setting: from the environment when it's set there (scripts/deploy.sh
# sets the stage), otherwise from the repo's .env (see .env.example).
#
# Only the names below are passed: anything given to Flutter is compiled
# into the app (readable in the web bundle), so secrets in .env must never
# be listed here. Add public identifiers only.
_allowed=(TABSCAN_STAGE)
_env="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.env"
DART_DEFINES=()
for _name in "${_allowed[@]}"; do
  _value="${!_name:-}"
  if [[ -z "$_value" && -f "$_env" ]]; then
    _value="$(sed -n "s/^${_name}=//p" "$_env" | tail -1)"
  fi
  [[ -n "$_value" ]] && DART_DEFINES+=(--dart-define="${_name}=${_value}")
done

# iOS signs with the developer's own team (IOS_DEVELOPMENT_TEAM in .env),
# written to a git-ignored xcconfig that Debug.xcconfig and Release.xcconfig
# include, so no one's personal team is committed. Not a dart-define.
_ios="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/tabscan_app/ios/Flutter/Private.xcconfig"
_value="${IOS_DEVELOPMENT_TEAM:-}"
[[ -z "$_value" && -f "$_env" ]] && _value="$(sed -n 's/^IOS_DEVELOPMENT_TEAM=//p' "$_env" | tail -1)"
if [[ "$_value" =~ ^[A-Z0-9]{10}$ ]]; then
  printf '// Generated by scripts/dart-defines.sh from .env; git-ignored.\nDEVELOPMENT_TEAM=%s\n' \
    "$_value" > "$_ios"
elif [[ -n "$_value" ]]; then
  echo "warning: IOS_DEVELOPMENT_TEAM isn't a 10-character team ID; iOS stays unsigned" >&2
fi
unset _allowed _env _name _value _ios
